CREATE TABLE donacion (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia          VARCHAR(64)    NOT NULL,
    donante_id          VARCHAR(64)    NOT NULL,
    monto               NUMERIC(12, 2) NOT NULL,
    moneda              VARCHAR(3)     NOT NULL,
    estado              VARCHAR(20)    NOT NULL,
    fecha_creacion      TIMESTAMP(6)   NOT NULL,
    fecha_actualizacion TIMESTAMP(6)   NOT NULL,
    link_pago           VARCHAR(1000)  NOT NULL,
    preferencia_id      VARCHAR(100),
    pago_id             VARCHAR(64),
    version             BIGINT         NOT NULL,
    CONSTRAINT uk_donacion_referencia UNIQUE (referencia),
    CONSTRAINT uk_donacion_pago_id UNIQUE (pago_id)
);

CREATE INDEX idx_donacion_donante_id ON donacion (donante_id);
CREATE INDEX idx_donacion_estado ON donacion (estado);
