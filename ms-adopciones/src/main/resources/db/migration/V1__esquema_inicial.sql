CREATE TABLE perfil (
    adoptante_id        VARCHAR(64)  PRIMARY KEY,
    nombre_completo     VARCHAR(150) NOT NULL,
    telefono            VARCHAR(40)  NOT NULL,
    provincia           VARCHAR(100) NOT NULL,
    localidad           VARCHAR(100) NOT NULL,
    direccion           VARCHAR(200) NOT NULL,
    tipo_vivienda       VARCHAR(20)  NOT NULL,
    tiene_patio         BOOLEAN      NOT NULL,
    hay_ninios          BOOLEAN      NOT NULL,
    hay_otros_animales  BOOLEAN      NOT NULL,
    fecha_actualizacion TIMESTAMP(6) NOT NULL
);

CREATE TABLE solicitud (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id               BIGINT       NOT NULL,
    animal_nombre           VARCHAR(100),
    adoptante_id            VARCHAR(64)  NOT NULL,
    estado                  VARCHAR(20)  NOT NULL,
    fecha_creacion          TIMESTAMP(6) NOT NULL,
    distancia_km            DOUBLE PRECISION,
    requiere_excepcion      BOOLEAN      NOT NULL,
    distancia_no_verificada BOOLEAN      NOT NULL,
    motivo_rechazo          VARCHAR(1000),
    justificacion_excepcion VARCHAR(1000),
    fecha_aprobacion        TIMESTAMP(6),
    fecha_entrega           TIMESTAMP(6),
    fecha_control           TIMESTAMP(6),
    resultado_control       VARCHAR(20),
    observaciones_control   VARCHAR(1000),
    motivo_cierre           VARCHAR(1000),
    animal_pendiente        BIGINT,
    adoptante_activo        VARCHAR(64),
    version                 BIGINT       NOT NULL,
    CONSTRAINT uk_solicitud_animal_pendiente UNIQUE (animal_pendiente),
    CONSTRAINT uk_solicitud_adoptante_activo UNIQUE (adoptante_activo)
);

CREATE TABLE solicitud_observacion (
    solicitud_id BIGINT       NOT NULL,
    orden        INTEGER      NOT NULL,
    texto        VARCHAR(500) NOT NULL,
    PRIMARY KEY (solicitud_id, orden),
    CONSTRAINT fk_solicitud_observacion_solicitud
        FOREIGN KEY (solicitud_id) REFERENCES solicitud (id)
);

CREATE TABLE evento_solicitud (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id    BIGINT       NOT NULL,
    fecha           TIMESTAMP(6) NOT NULL,
    estado_anterior VARCHAR(20),
    estado_nuevo    VARCHAR(20)  NOT NULL,
    actor           VARCHAR(64)  NOT NULL,
    detalle         VARCHAR(1000),
    CONSTRAINT fk_evento_solicitud_solicitud
        FOREIGN KEY (solicitud_id) REFERENCES solicitud (id)
);

CREATE INDEX idx_solicitud_adoptante_id ON solicitud (adoptante_id);
CREATE INDEX idx_solicitud_animal_id ON solicitud (animal_id);
CREATE INDEX idx_solicitud_estado ON solicitud (estado);
CREATE INDEX idx_evento_solicitud_solicitud_id ON evento_solicitud (solicitud_id);
