CREATE TABLE animal (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                    VARCHAR(100) NOT NULL,
    especie                   VARCHAR(20)  NOT NULL,
    edad_meses                INTEGER      NOT NULL,
    tamanio                   VARCHAR(20)  NOT NULL,
    necesidades_especiales    VARCHAR(500),
    apto_ninios               BOOLEAN      NOT NULL,
    apto_otros_animales       BOOLEAN      NOT NULL,
    requiere_espacio_exterior BOOLEAN      NOT NULL,
    estado                    VARCHAR(20)  NOT NULL,
    motivo_no_disponible      VARCHAR(500),
    fecha_alta                TIMESTAMP(6) NOT NULL,
    fecha_actualizacion       TIMESTAMP(6) NOT NULL,
    version                   BIGINT       NOT NULL
);

CREATE INDEX idx_animal_estado ON animal (estado);
CREATE INDEX idx_animal_especie ON animal (especie);
